import { BlockType, GridPosition, LevelConfig, SubscriptionTier } from './types';

type WorkshopLevel = Pick<LevelConfig,
  'id' | 'title' | 'mission' | 'tutorialMessage' | 'explanation' | 'maxBlocks' | 'availableBlocks'
> & { map: string[] };

// S marca a saída de Sparky, G a bandeira, T um alvo de pintura e # uma parede.
const defineWorkshopLevel = ({ map, ...level }: WorkshopLevel): LevelConfig => {
  const cells = map.flatMap((row, y) => Array.from(row, (tile, x) => ({ tile, x, y })));
  const positionsFor = (tile: string): GridPosition[] => cells
    .filter(cell => cell.tile === tile)
    .map(({ x, y }) => ({ x, y }));

  const [startPos] = positionsFor('S');
  const [goalPos] = positionsFor('G');
  const paintTargets = positionsFor('T');

  return {
    ...level,
    gridSize: map.length,
    startPos,
    goalPos,
    obstacles: positionsFor('#'),
    ...(paintTargets.length > 0 ? { paintTargets } : {}),
    ageGroup: '11-14',
    requiredSubscription: SubscriptionTier.PRO,
  };
};

